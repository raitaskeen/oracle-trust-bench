//! The committed pilot specs are valid, and `protocol/ORACLE_MATRIX.md`
//! matches what the specs say.

use std::path::{Path, PathBuf};

use otb_core::spec::{TaskSpec, load_all, render_matrix_markdown};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The generated part of the matrix file starts after this marker line.
const MARKER: &str = "<!-- generated by `otb matrix`; do not edit below -->\n";

fn specs() -> Vec<TaskSpec> {
    load_all(&root().join("tasks")).expect("load tasks")
}

#[test]
fn all_pilot_specs_are_valid() {
    let specs = specs();
    let ids: Vec<&str> = specs.iter().map(|s| s.id.as_str()).collect();
    assert_eq!(
        ids,
        [
            "MLDSA-T41-power2round",
            "MLDSA-T47-make-hint",
            "MLKEM-T01-ntt",
            "MLKEM-T07-compress-d",
            "MLKEM-T24-decaps-implicit-rejection",
        ]
    );
    for s in &specs {
        assert_eq!(s.problems(), Vec::<String>::new(), "{}", s.id);
    }
}

#[test]
fn oracle_matrix_file_is_up_to_date() {
    let text = std::fs::read_to_string(root().join("protocol/ORACLE_MATRIX.md"))
        .expect("protocol/ORACLE_MATRIX.md")
        .replace("\r\n", "\n");
    let (_, generated) = text.split_once(MARKER).expect("marker line");
    assert_eq!(
        generated,
        render_matrix_markdown(&specs()),
        "run `otb matrix --write` to regenerate"
    );
}
