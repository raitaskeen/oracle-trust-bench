//! The `otb` command. Each subcommand is a thin layer over the library crates.

use std::path::PathBuf;
use std::process::ExitCode;

mod budget;

use clap::{Parser, Subcommand};
use otb_core::spec::{load_all, render_matrix_markdown};

#[derive(Parser)]
#[command(name = "otb", version, about = "oracle-trust-bench harness")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Task specification commands.
    Tasks {
        #[command(subcommand)]
        command: TasksCommand,
    },
    /// Recompute the API credit request (port of analysis/budget.py).
    Budget,
    /// Reference implementation commands.
    Ref {
        #[command(subcommand)]
        command: RefCommand,
    },
    /// Print the task-by-oracle applicability matrix.
    Matrix {
        /// Directory holding the task specs.
        #[arg(long, default_value = "tasks")]
        tasks: PathBuf,
        /// Rewrite the generated part of this file instead of printing.
        #[arg(long, value_name = "FILE")]
        write: Option<PathBuf>,
    },
}

#[derive(Subcommand)]
enum TasksCommand {
    /// Parse every spec and check it against the schema and the FIPS tables.
    Validate {
        /// Directory holding the task specs.
        #[arg(long, default_value = "tasks")]
        tasks: PathBuf,
    },
}

#[derive(Subcommand)]
enum RefCommand {
    /// Run the C references through the oracles implemented so far and
    /// compare with the spec-literal code and the ACVP vectors.
    Run {
        /// Sandbox backend: `docker` (default) or `unshare` (weaker).
        #[arg(long, default_value = "docker")]
        backend: String,
        /// Docker image ID; defaults to $OTB_SANDBOX_IMAGE.
        #[arg(long)]
        image: Option<String>,
    },
}

fn backend_from(name: &str, image: Option<String>) -> Result<otb_sandbox::Backend, String> {
    match name {
        "docker" => {
            let image = image
                .or_else(|| std::env::var("OTB_SANDBOX_IMAGE").ok())
                .ok_or("docker backend needs --image or OTB_SANDBOX_IMAGE")?;
            Ok(otb_sandbox::Backend::Docker { image })
        }
        "unshare" => Ok(otb_sandbox::Backend::UnshareWeaker),
        other => Err(format!("unknown backend {other:?} (use docker or unshare)")),
    }
}

fn ref_run(backend: otb_sandbox::Backend) -> ExitCode {
    let repo = std::env::current_dir().expect("current directory");
    println!("backend: {}", backend.name());
    let h = otb_harness::Harness { repo, backend };
    let mut failed = false;
    for r in otb_harness::reference::run_all(&h) {
        match r {
            Ok(r) => {
                let status = match &r.outcome {
                    otb_core::Outcome::Pass => "pass".to_owned(),
                    other => {
                        failed = true;
                        format!("{other:?}")
                    }
                };
                println!(
                    "{:38} {:24} {:5} {} cases",
                    r.task,
                    r.oracle.name(),
                    status,
                    r.cases
                );
                for (group, n) in &r.groups {
                    println!("{:38}   {group}: {n}", "");
                }
            }
            Err(e) => {
                failed = true;
                println!("HARNESS ERROR: {e}");
            }
        }
    }
    println!(
        "not yet implemented: malformed-input, implicit-rejection (M4); ct-valgrind, ct-static-division (M5a); ct-dudect (nightly)"
    );
    if failed {
        ExitCode::FAILURE
    } else {
        ExitCode::SUCCESS
    }
}

const MARKER: &str = "<!-- generated by `otb matrix`; do not edit below -->\n";

fn main() -> ExitCode {
    match run(Cli::parse()) {
        Ok(code) => code,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::from(2)
        }
    }
}

fn run(cli: Cli) -> Result<ExitCode, Box<dyn std::error::Error>> {
    match cli.command {
        Command::Tasks {
            command: TasksCommand::Validate { tasks },
        } => {
            let specs = load_all(&tasks)?;
            let mut bad = 0usize;
            for s in &specs {
                let problems = s.problems();
                if problems.is_empty() {
                    println!("ok    {}", s.id);
                } else {
                    bad += 1;
                    println!("FAIL  {}", s.id);
                    for p in problems {
                        println!("      - {p}");
                    }
                }
            }
            println!(
                "{} specs, {} valid, {} invalid",
                specs.len(),
                specs.len() - bad,
                bad
            );
            Ok(if bad == 0 && !specs.is_empty() {
                ExitCode::SUCCESS
            } else {
                ExitCode::FAILURE
            })
        }
        Command::Budget => {
            print!("{}", budget::render());
            Ok(ExitCode::SUCCESS)
        }
        Command::Ref {
            command: RefCommand::Run { backend, image },
        } => Ok(ref_run(backend_from(&backend, image)?)),
        Command::Matrix { tasks, write } => {
            let generated = render_matrix_markdown(&load_all(&tasks)?);
            match write {
                None => print!("{generated}"),
                Some(path) => {
                    let text = std::fs::read_to_string(&path)?.replace("\r\n", "\n");
                    let (head, _) = text
                        .split_once(MARKER)
                        .ok_or("file has no generated-section marker")?;
                    std::fs::write(&path, format!("{head}{MARKER}{generated}"))?;
                    println!("wrote {}", path.display());
                }
            }
            Ok(ExitCode::SUCCESS)
        }
    }
}
